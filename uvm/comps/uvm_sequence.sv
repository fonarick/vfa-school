`ifndef					UVM_SEQUENCE_SV
`define					UVM_SEQUENCE_SV
// —————————————————————————|———————————————————————————|———————————————————————————
// ————————————————————————————————————————————————————————— uvm - comps - sequence
// —————————————————————————————————————————————————————————————————————————————————
class					uvm_sequence				   #(
	type					T			  =	uvm_sequence_item
) extends uvm_object									;
// —————————————————————————————————————————————————————
T							req, rsp					;
uvm_seq_item_export #(T)	m_sequencer					;
// —————————————————————————————————————————————————————
// ————————— (string)
// —————————————————————————————————————————————————————
function				new								(
	string					name		  =	""
)														;
	super.new(name)										;
endfunction
// —————————————————————————————————————————————————————
// ————————— start(uvm_sequencer #(T)): void
// —————————————————————————————————————————————————————
task					start							(
	uvm_sequencer #(T)		sequencer
)														;
	m_sequencer							  =	sequencer.seq_item_export;
	body()												;
endtask
// —————————————————————————————————————————————————————
// ————————— start_item(output T): void
// —————————————————————————————————————————————————————
task					start_item						(
	output T				t
)														;
	if (t == null)
		t								  =	new()		;
endtask
// —————————————————————————————————————————————————————
// ————————— finish_item(T): void
// —————————————————————————————————————————————————————
task					finish_item						(
	T						t
)														;
	m_sequencer.send_request(t)							;
	m_sequencer.wait_for_item_done()					;
endtask
// —————————————————————————————————————————————————————
// ————————— body(): void
// —————————————————————————————————————————————————————
virtual task			body							(
)														;
endtask
// —————————————————————————————————————————————————————
endclass
// —————————————————————————|———————————————————————————|———————————————————————————
`endif
`ifndef					UVM_ANALYSIS_IMP_SV
`define					UVM_ANALYSIS_IMP_SV
// —————————————————————————|———————————————————————————|———————————————————————————
// ————————————————————————————————————————————————————————— uvm - tlm - analysis_imp
// —————————————————————————————————————————————————————————————————————————————————
virtual class			uvm_analysis_imp_base		   #(
	type					T			  =	int
)														;
// —————————————————————————————————————————————————————
pure virtual function void write						(
	input T					t
)														;
// —————————————————————————————————————————————————————
endclass
// —————————————————————————————————————————————————————————————————————————————————
class					uvm_analysis_imp			   #(
	type					T			  =	int			,
	type					IMP			  =	int
) extends uvm_analysis_imp_base #(T)					;
// —————————————————————————————————————————————————————
local IMP					m_imp						;
// —————————————————————————————————————————————————————
// ————————— (string, IMP)
// —————————————————————————————————————————————————————
function				new								(
	string					name						,
	IMP						imp
)														;
	m_imp								  =	imp			;
endfunction
// —————————————————————————————————————————————————————
// ————————— write(T): void
// —————————————————————————————————————————————————————
virtual function void	write							(
	T						t
)														;
	m_imp.write(t)										;
endfunction
// —————————————————————————————————————————————————————
endclass
// —————————————————————————|———————————————————————————|———————————————————————————
`endif
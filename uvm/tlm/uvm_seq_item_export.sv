`ifndef					UVM_SEQ_ITEM_EXPORT_SV
`define					UVM_SEQ_ITEM_EXPORT_SV
// —————————————————————————|———————————————————————————|———————————————————————————
// ————————————————————————————————————————————————————————— uvm - tlm - seq_item_export
// —————————————————————————————————————————————————————————————————————————————————
class					uvm_seq_item_export			   #(
	type					T			  =	int
)														;
// —————————————————————————————————————————————————————
mailbox #(T)				m_req_mbx					;
event						m_item_done_ev				;
// —————————————————————————————————————————————————————
// ————————— (string, uvm_component)
// —————————————————————————————————————————————————————
function				new								(
	string					name		  =	""			,
	uvm_component			parent		  =	null
)														;
	m_req_mbx							  =	new()		;
endfunction
// —————————————————————————————————————————————————————
// ————————— send_request(T): void
// —————————————————————————————————————————————————————
task					send_request					(
	T						req
)														;
	m_req_mbx.put(req)									;
endtask
// —————————————————————————————————————————————————————
// ————————— get_next_item(output T): void
// —————————————————————————————————————————————————————
task					get_next_item					(
	output T				req
)														;
	m_req_mbx.get(req)									;
endtask
// —————————————————————————————————————————————————————
// ————————— item_done(): void
// —————————————————————————————————————————————————————
function void			item_done						(
)														;
	-> m_item_done_ev									;
endfunction
// —————————————————————————————————————————————————————
// ————————— wait_for_item_done(): void
// —————————————————————————————————————————————————————
task					wait_for_item_done				(
)														;
	@(m_item_done_ev)									;
endtask
// —————————————————————————————————————————————————————
endclass
// —————————————————————————|———————————————————————————|———————————————————————————
`endif
// —————————————————————————|———————————————————————————|———————————————————————————
// ————————————————————————————————————————————————————————— uvm - tlm - analysis_port
// —————————————————————————————————————————————————————————————————————————————————
class					uvm_analysis_port			   #(
	type					T			  =	int
)														;
// —————————————————————————————————————————————————————
uvm_analysis_imp #(T)		m_imps					 [$];
// —————————————————————————————————————————————————————
// ————————— connect(uvm_analysis_imp #(T)): void
// —————————————————————————————————————————————————————
function void			connect							(
	uvm_analysis_imp #(T)	imp
)														;
	m_imps.push_back(imp)								;
endfunction
// —————————————————————————————————————————————————————
// ————————— write(T): void
// —————————————————————————————————————————————————————
function void			write							(
	T						t
)														;
	foreach (m_imps[i])
		m_imps[i].write(t)								;
endfunction
// —————————————————————————————————————————————————————
endclass
// —————————————————————————|———————————————————————————|———————————————————————————
`endif